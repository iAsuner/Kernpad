const fs=require('fs'),vm=require('vm'),assert=require('assert/strict'),path=require('path');
const context={};vm.createContext(context);vm.runInContext(fs.readFileSync(path.join(__dirname,'../Web/document-values.js'),'utf8'),context);
const {cloneDocumentValue:clone,equalDocumentValues:equal,documentValueBytes:bytes}=context;
let count=0;const check=(label,value)=>{assert.ok(value,label);count++;};
const media='data:image/png;base64,'+'A'.repeat(2*1024*1024);
const record={id:'synthetic',fields:[{key:'password',value:'synthetic-only',secret:true}],blocks:[{type:'image',data:media,layout:{span:6}},{type:'text',text:'first'}],refs:['linked']};
const copy=clone(record);check('copied record is equal',equal(record,copy));
copy.fields[0].value='changed';copy.blocks[0].layout.span=12;copy.refs.push('another');
check('mutable nested containers are independent',record.fields[0].value==='synthetic-only'&&record.blocks[0].layout.span===6&&record.refs.length===1);
check('content changes compare unequal',!equal(record,copy));
check('same media remains exact',copy.blocks[0].data===media);
check('replacing media is detected',!equal(record,{...record,blocks:[{...record.blocks[0],data:media+'B'},record.blocks[1]]}));
check('key ordering does not create a false change',equal({a:1,b:2},{b:2,a:1}));
check('missing and explicit undefined stay distinct',!equal({a:undefined},{}));
check('array order is meaningful',!equal([1,2],[2,1]));
check('array lengths are meaningful even with empty slots',!equal(new Array(1),[]));
check('arrays cannot equal plain objects',!equal([1],{0:1}));
check('null false and zero remain distinct',!equal(null,false)&&!equal(false,0));
const unusual=JSON.parse('{"__proto__":{"safe":"value"},"constructor":"literal"}');
check('own prototype-named fields are copied as data',Object.hasOwn(clone(unusual),'__proto__')&&equal(unusual,clone(unusual)));
const snapshots=Array.from({length:50},()=>clone(record));
check('unchanged attachment is counted once across history',bytes(snapshots)<bytes(record)+100000);
snapshots[0].blocks[0].data=media+'different';
check('replaced attachments count toward the history budget',bytes(snapshots)>bytes(record)*1.9);
check('snapshots do not keep serialized duplicates',!Object.hasOwn(snapshots[0],'json'));
console.log(`${count} document copy / equality / shared attachment checks passed`);
